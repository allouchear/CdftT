void Orbitals::Save(std::string& tag)
{
    if(tag.find(".wfx")!=std::string::npos)
        Save_wfx(tag);
    else if(tag.find(".molden")!=std::string::npos)
        Save_molden(tag);
    else if(tag.find(".gab")!=std::string::npos)
        Save_gab(tag);
    else
    {
        std::cout<<"Format not recognize, please choose a valide format"<<std::endl;
        std::exit(1);
    }
}

void Orbitals::Save_wfx(std::string& tag)
{
    int n, nMO;
    std::ofstream s;
    s.open(tag);

    s<<"<Title>"<<std::endl;
    s<<" Input file generated by cdftt..."<<std::endl;
    s<<"</Title>"<<std::endl;

    s<<"<Keywords>"<<std::endl;
    s<<" GTO"<<std::endl;
    s<<"</Keywords>"<<std::endl;

    s<<"<Number of Nuclei>"<<std::endl;
    s<<" "<<_numberOfAtoms<<std::endl;
    s<<"</Number of Nuclei>"<<std::endl;

    s<<"<Number of Occupied Molecular Orbitals>"<<std::endl;
    if(!_alphaAndBeta)
        nMO=_numberOfMo*2;
    else
        nMO=_numberOfMo;
    s<<" "<<nMO<<std::endl;
    s<<"</Number of Occupied Molecular Orbitals>"<<std::endl;

    s<<"<Number of Perturbations>"<<std::endl;
    s<<" 0"<<std::endl;
    s<<"</Number of Perturbations>"<<std::endl;

    s<<"<Net Charge>"<<std::endl;
    s<<" 0"<<std::endl;
    s<<"</Net Charge>"<<std::endl;

    s<<"<Number of Electrons>"<<std::endl;
    s<<" "<<_numberOfAlphaElectrons+_numberOfBetaElectrons<<std::endl;
    s<<"</Number of Electrons>"<<std::endl;

    s<<"<Number of Alpha Electrons>"<<std::endl;
    s<<" "<<_numberOfAlphaElectrons<<std::endl;
    s<<"</Number of Alpha Electrons>"<<std::endl;

    s<<"<Number of Beta Electrons>"<<std::endl;
    s<<" "<<_numberOfBetaElectrons<<std::endl;
    s<<"</Number of Beta Electrons>"<<std::endl;

    s<<"<Nuclear Names>"<<std::endl;
    for(int i=0; i<_numberOfAtoms; i++)
        s<<" "<<_symbol[i]<<i+1<<std::endl;
    s<<"</Nuclear Names>"<<std::endl;

    s<<"<Atomic Numbers>"<<std::endl;
    for(int i=0; i<_numberOfAtoms; i++)
        s<<" "<<_atomicNumbers[i]<<std::endl;
    s<<"</Atomic Numbers>"<<std::endl;    

    s<<"<Nuclear Charges>"<<std::endl;
    for(int i=0; i<_numberOfAtoms; i++)
        s<<std::right<<std::scientific<<std::setprecision(12)<<" "<<std::setw(20)<<double(_atomicNumbers[i])<<std::endl;
    s<<"</Nuclear Charges>"<<std::endl;

    s<<"<Nuclear Cartesian Coordinates>"<<std::endl;
    for(int i=0; i<_numberOfAtoms; i++)
    {
        for(int j=i*3; j<(i+1)*3; j++)
            s<<std::right<<std::scientific<<std::setprecision(12)<<" "<<std::setw(20)<<_coordinates[j];
        s<<std::endl;
    }
    s<<"</Nuclear Cartesian Coordinates>"<<std::endl;

    s<<"<Number of Primitives>"<<std::endl;
    s<<" "<<_numberOfGtf<<std::endl;
    s<<"</Number of Primitives>"<<std::endl;

    s<<"<Primitive Centers>"<<std::endl;

    if(int(_vcgtfNonNormalise.size())==_numberOfGtf)
        for(int i=0; i<_numberOfGtf; i++)
        {
            s<<"\t"<<_primitiveCenters[i];
            if((i+1)%5==0)
                s<<std::endl;
        }
    else
    {
        vector<int> pc;
        for(size_t i=0; i<_vcgtf.size(); i++)
            for(int j=0; j<_vcgtf[i].numberOfFunctions(); j++)
                pc.push_back(_vcgtf[i].NumCenter());

        for(int i=0; i<_numberOfGtf; i++)
        {
            s<<"\t"<<pc[i];
            if((i+1)%5==0)
                s<<std::endl;
        }
    }
    s<<std::endl;
    s<<"</Primitive Centers>"<<std::endl;

    n=0;
    s<<"<Primitive Types>"<<std::endl;
    for(size_t i=0; i<_vcgtf.size(); i++)
        for(int j=0; j<_vcgtf[i].numberOfFunctions(); j++)
        {
            s<<"\t"<<getwfxType(_vcgtf[i].gtf()[j].get_l());
            if((n+1)%5==0)
                s<<std::endl;
            n++;
        }
    s<<std::endl;
    s<<"</Primitive Types>"<<std::endl;

    n=0;
    s<<"<Primitive Exponents>"<<std::endl;
    for(size_t i=0; i<_vcgtf.size(); i++)
        for(int j=0; j<_vcgtf[i].numberOfFunctions(); j++)
        {
            s<<std::right<<std::scientific<<std::setprecision(12)<<"\t"<<std::setw(20)<<_vcgtf[i].gtf()[j].get_exponent();
            if((n+1)%5==0)
                s<<std::endl;
            n++;
        }
    s<<std::endl;
    s<<"</Primitive Exponents>"<<std::endl;

    int m;

    if(_alphaAndBeta)
        m=1;
    else
        m=2;

    s<<"<Molecular Orbital Occupation Numbers>"<<std::endl;
    for(int i=0; i<m; i++)
        for(int j=0; j<_numberOfMo; j++)
            s<<" "<<_occupationNumber[i][j]<<std::endl;
    s<<"</Molecular Orbital Occupation Numbers>"<<std::endl;

    s<<"<Molecular Orbital Energies>"<<std::endl;
    for(int i=0; i<m; i++)
        for(size_t j=0; j<_orbitalEnergy[i].size(); j++)
            s<<std::right<<std::scientific<<std::setprecision(12)<<" "<<std::setw(20)<<_orbitalEnergy[i][j]<<std::endl;
    s<<"</Molecular Orbital Energies>"<<std::endl;

    s<<"<Molecular Orbital Spin Types>"<<std::endl;
    if(m==1)
        for(int i=0; i<_numberOfMo; i++)
            s<<" "<<"Alpha and Beta"<<std::endl;
    else
    {
        for(size_t i=0; i<_orbitalEnergy[0].size(); i++)
            s<<" "<<"Alpha"<<std::endl;
        for(size_t i=0; i<_orbitalEnergy[1].size(); i++)
            s<<" "<<"Beta"<<std::endl;
    }
    s<<"</Molecular Orbital Spin Types>"<<std::endl;

    s<<"<Molecular Orbital Primitive Coefficients>"<<std::endl;
    int a=0,b=0;
    for(int i=0; i<m; i++)
        for(int j=0; j<_numberOfMo; j++)
        {
            a++;
            s<<"<MO Number>"<<std::endl;
            s<<" "<<a<<std::endl;
            s<<"</MO Number>"<<std::endl;
        
            for(size_t k=0; k<_vcgtf.size(); k++)
                for(int l=0; l<_vcgtf[k].numberOfFunctions(); l++)
                {
                    s<<std::right<<std::scientific<<std::setprecision(12)<<" "<<std::setw(20)<<_vcgtf[k].coefficients()[l]*_vcgtf[k].gtf()[l].get_coefficient()*_coefficients[i][j][k];

                    if((b+1)%4==0)
                        s<<std::endl;
                    b++;
                }

            if(b%4!=0)
                s<<std::endl;
        }
    s<<"</Molecular Orbital Primitive Coefficients>"<<std::endl;

    s<<"<Energy = T + Vne + Vee + Vnn>"<<std::endl;
    s<<" "<<_energy<<std::endl;
    s<<"</Energy = T + Vne + Vee + Vnn>"<<std::endl;

    s<<"<Virial Ratio (-V/T)>"<<std::endl;
    s<<" "<<std::scientific<<std::setprecision(12)<<2<<std::endl;
    s<<"</Virial Ratio (-V/T)>"<<std::endl;

    s.close();
}
